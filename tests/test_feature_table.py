"""`support/FEATURES.md`, the generated promotion table of every experimental
feature, is current, and the script's own `CXX` table is held to the code.

The table is generated by `scripts/feature_table.py` from the registry
(`momwire._features`), `support/hierarchy.toml` and the executables' main
(`standalone/momwire_razor2p.cpp`); this regenerates it and compares.
"""

from __future__ import annotations

import importlib.util
import re
from pathlib import Path

import pytest

from momwire import _features as F

ROOT = Path(__file__).resolve().parents[1]
SCRIPT = ROOT / "scripts" / "feature_table.py"
TABLE = ROOT / "support" / "FEATURES.md"


@pytest.fixture(scope="module")
def ft():
    spec = importlib.util.spec_from_file_location("feature_table", SCRIPT)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_the_feature_table_is_current(ft):
    if importlib.util.find_spec("tomllib") is None:  # Python 3.10
        pytest.importorskip("tomli")
    expected = ft.render(
        F.FEATURES,
        ft.load_levels(),
        ft.EXE_SOURCE.read_text(encoding="utf-8"),
        F.DEEPEST,
    )
    current = TABLE.read_text(encoding="utf-8") if TABLE.exists() else ""
    assert current == expected, (
        f"support/FEATURES.md is stale; regenerate it with: {ft.REGENERATE}"
    )


def test_every_feature_has_one_row(ft):
    text = TABLE.read_text(encoding="utf-8")
    rows = re.findall(r"^\| `([a-z0-9_]+)` \| #\d+ ", text, re.M)
    assert rows == list(F.FEATURES)


def test_the_cxx_table_names_every_feature_and_existing_files(ft):
    assert set(ft.CXX) == set(F.FEATURES)
    for name, (where, files) in ft.CXX.items():
        assert where in ("exe", "extension", "none"), name
        assert bool(files) == (where != "none"), name
        for path in files:
            assert (ROOT / path).is_file(), (name, path)


def test_the_cxx_tables_exe_rows_are_the_evaluators_switches(ft):
    # "exe route" means a switch of `ni_eval::Features`, the C++ route the
    # executables build; hold the script's rows to that struct's fields.
    header = (ROOT / "src" / "momwire" / "_near_interface_eval.h").read_text(
        encoding="utf-8"
    )
    body = re.search(r"struct Features \{(.*?)\n\};", header, re.S)
    assert body is not None
    fields = set(re.findall(r"bool (\w+) = false;", body[1]))
    assert fields
    assert {n for n, (w, _f) in ft.CXX.items() if w == "exe"} == fields


def test_what_the_executables_carry_has_exe_cxx(ft):
    # An EXE_FEATURES row with no exe route would be a table entry the
    # executables cannot honour.
    rows = ft.exe_rows(ft.EXE_SOURCE.read_text(encoding="utf-8"))
    assert all(ft.CXX[n][0] == "exe" for n in rows), rows
