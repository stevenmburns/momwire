ORDINARY = {
    "dipole": (
        [np.array([(0.0, 0.0, -2.0), (0.0, 0.0, 2.0)])],
        [[40]],
        8.0,
        0.01,
        [(0, 2.0, 1 + 0j)],
    ),
    "invvee": (
        [np.array([(-1.6, 0.0, 0.6), (0.0, 0.0, 1.9), (1.6, 0.0, 0.6)])],
        [[20, 20]],
        8.0,
        0.01,
        [(0, 2.06, 1 + 0j)],
    ),
}


def _solve(wires, nspec, lam, radius, feeds, degree, *, chunked=True, mem=None):
    kw = {} if mem is None else {"swept_mem_mb": mem}
    old = _bs._SAME_EDGE_CORR_CHUNKED
    _bs._SAME_EDGE_CORR_CHUNKED = chunked
    try:
        return complex(
            BSplineSolver(
                wires=wires,
                n_per_edge_per_wire=nspec,
                wavelength=lam,
                wire_radius=radius,
                feeds=feeds,
                degree=degree,
                **kw,
            ).compute_impedance()[0]
        )
    finally:
        _bs._SAME_EDGE_CORR_CHUNKED = old


@pytest.mark.parametrize("degree", [1, 2])
@pytest.mark.parametrize("name", sorted(ORDINARY))
def test_windowing_did_not_disturb_an_ordinary_deck(name, degree):
    """Still bit-identical between routes: an edge that fits one window takes
    one window, and one window of a whole edge is the whole edge."""
    w, n, lam, rad, feeds = ORDINARY[name]
    assert _solve(w, n, lam, rad, feeds, degree, chunked=True) == _solve(
        w, n, lam, rad, feeds, degree, chunked=False
    )


@pytest.mark.parametrize("degree", [1, 2])
def test_the_long_wire_stays_inside_its_reassociation_bound(degree):
    n, mem = 1200, 4
    zc = _solve(
        LONG_WIRE,
        [[n]],
        LONG_LAM,
        5e-6,
        [(0, 2000.0, 1 + 0j)],
        degree,
        chunked=True,
        mem=mem,
    )
    zd = _solve(
        LONG_WIRE,
        [[n]],
        LONG_LAM,
        5e-6,
        [(0, 2000.0, 1 + 0j)],
        degree,
        chunked=False,
        mem=mem,
    )
    assert zc == pytest.approx(zd, rel=1e-11), f"{zc!r} vs {zd!r}"


