# G-968-4: the default route, and what it saves
# ---------------------------------------------------------------------


def test_a_default_solve_windows_the_static_and_reg_blocks(monkeypatch):
    """Counted at the producers, with nothing in the test touching a switch."""
    rows_seen = []
    real_st = _bs._seg_seg_static_moments
    real_geo = _bs._seg_seg_reg_geometry

    def spy_st(seg, a, max_d, *, ek=None, rows=None):
        rows_seen.append(("static", rows))
        return real_st(seg, a, max_d, ek=ek, rows=rows)

    def spy_geo(seg, a, max_d, n_qp, *, ek=None, rows=None):
        rows_seen.append(("reg", rows))
        return real_geo(seg, a, max_d, n_qp, ek=ek, rows=rows)

    monkeypatch.setattr(_bs, "_seg_seg_static_moments", spy_st)
    monkeypatch.setattr(_bs, "_seg_seg_reg_geometry", spy_geo)
    n, mem = 1200, 4
    BSplineSolver(
        wires=LONG_WIRE,
        n_per_edge_per_wire=[[n]],
        wavelength=LONG_LAM,
        wire_radius=5e-6,
        feeds=[(0, 2000.0, 1 + 0j)],
        degree=2,
        swept_mem_mb=mem,
    ).compute_impedance()
    for kind in ("static", "reg"):
        calls = [r for k, r in rows_seen if k == kind]
        assert len(calls) > 1, f"{kind} was built {len(calls)} time(s), not windowed"
        assert all(r is not None for r in calls), f"{kind} took a whole-edge call"
        assert all(r.stop - r.start < n for r in calls), (
            f"a {kind} window covered the whole {n}-segment edge: {calls}"
        )


def test_the_toeplitz_table_is_memoised_across_a_window_loop():
    """G-968-5. Without this the windowed static path is 3.7x slower across an
    edge than the single square call — the table is the work, the gather is a
    copy."""
    _static_toeplitz_table.cache_clear()
    before = _static_toeplitz_table.cache_info()
    h, a, N, max_d = 0.5, 5e-4, 60, 2
    seg = np.arange(N + 1) * h
    for r0 in range(0, N, 10):
        _seg_seg_static_moments(seg, a, max_d, rows=slice(r0, min(r0 + 10, N)))
    after = _static_toeplitz_table.cache_info()
    assert after.misses - before.misses == 1, (
        f"the table was built {after.misses - before.misses} times for one edge"
    )
    assert after.hits - before.hits == 5, after


# --- the memory ratio, one process per arm (the #967 instrument) ---------
#
# `tracemalloc` peak, never `ru_maxrss`: a forked child inherits its parent's
# high-water mark, which made an absolute RSS gate report 1,610 MB for an arm
# that takes 900 MB alone (momwire#967). Ratios, so the gate measures the
# change and not the box.
#
# Measured on this box at N=1500, d=2, 64 MB budget:
#   windowed (ships)        338 MB
#   whole-edge A_st/A_reg   811 MB    ratio 2.40
_MEM_N, _MEM_DEGREE, _MEM_MEM = 1500, 2, 64
_WHOLE_EDGE_MIN_RATIO = 1.5
_SHIPPED_MAX_MB = 600.0

_ARM = textwrap.dedent(
    """
    import sys, tracemalloc
    import numpy as np
    import momwire.bspline as bs
    bs._SAME_EDGE_WINDOW_BLOCKS = sys.argv[1] == "1"
    tracemalloc.start()
    bs.BSplineSolver(
        wires=[np.array([(0.0, 0.0, 0.0), (0.0, 4000.0, 0.0)])],
        n_per_edge_per_wire=[[%d]],
        wavelength=%r,
        wire_radius=5e-6,
        feeds=[(0, 2000.0, 1 + 0j)],
        degree=%d,
        swept_mem_mb=%d,
    ).compute_impedance()
    print(tracemalloc.get_traced_memory()[1] / 1e6)
    """
) % (_MEM_N, LONG_LAM, _MEM_DEGREE, _MEM_MEM)


def _arm_peak_mb(windowed):
    import os

    env = dict(os.environ)
    env.update(OMP_NUM_THREADS="1", OPENBLAS_NUM_THREADS="1", MKL_NUM_THREADS="1")
    done = subprocess.run(
        [sys.executable, "-c", _ARM, "1" if windowed else "0"],
        capture_output=True,
        text=True,
        env=env,
        cwd=str(Path(__file__).resolve().parents[1]),
    )
    assert done.returncode == 0, done.stderr[-2000:]
    return float(done.stdout.strip().splitlines()[-1])


@pytest.mark.slow
def test_windowing_the_blocks_is_what_saves_the_memory():
    shipped = _arm_peak_mb(True)
    whole = _arm_peak_mb(False)
    assert shipped < _SHIPPED_MAX_MB, f"shipped route traced {shipped:.0f} MB"
    ratio = whole / shipped
    assert ratio > _WHOLE_EDGE_MIN_RATIO, (
        f"building A_st/A_reg whole-edge cost {whole:.0f} MB against the "
        f"windowed {shipped:.0f} MB — a ratio of {ratio:.2f}, under the "
        f"{_WHOLE_EDGE_MIN_RATIO:.2f} this gate needs to tell them apart"
    )


def test_windowing_is_the_default():
    assert _bs._SAME_EDGE_WINDOW_BLOCKS is True
