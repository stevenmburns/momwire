"""The rectangular same-edge window (momwire#968), #966's other half.

#967 chunked the same-edge correction over observer rows but left `A_st` and
`A_reg` whole-edge, because the C++ reg kernel validated `R.shape ==
(N*n_qp, N*n_qp)` and refused a rectangular window. Those two were most of the
3.9 GB that remained on a 4,001-segment single wire.

The kernel never actually needed square: its observer (`i`) and source (`j`)
axes were independent throughout — `wu(p,i,q)` on one side, `wu(P,j,r)` on the
other. So the generalisation is a separate row-side and column-side `wu_pow`,
with the square entry point passing one array twice and executing the identical
instruction stream. The static block is Toeplitz, so its window is a GATHER of
the same 2N-1 table.

Gates:

- G-968-1  every window equals the square answer's sub-block EXACTLY, across
           degrees, n_qp, EK on/off, accelerator on/off, and edge windows —
           including the degenerate empty and full-height ones.
- G-968-2  the square C++ entry points still answer what they answered before
           the change. Banked from a pre-change build and compared after
           rebuilding, not reasoned about (the momwire#762 protocol).
- G-968-3  chunked == dense bit-identically on ordinary decks and within the
           reassociation bound on the long wire — #967's statement, unmoved.
- G-968-4  the windowed route is what a default solve takes, counted at the
           producer, and the memory it saves is real: tracemalloc-peak RATIO
           between arms, one process each.
- G-968-5  the Toeplitz table is memoised across a window loop, because
           rebuilding it per window measured 3.7x slower across an edge than
           the single square call.

The oracle for G-968-2 is regenerated by `scripts/bank_same_edge_oracle.py`
against a build of the PREVIOUS commit; it is committed as a fixture so the
gate does not need two builds to run.
"""

import itertools
import subprocess
import sys
import textwrap
from pathlib import Path

import numpy as np
import pytest

import momwire._bspline_kernels as bk
import momwire.bspline as _bs
from momwire._accel import acc as _acc
from momwire._bspline_kernels import (
    _EK,
    _seg_seg_reg_geometry,
    _seg_seg_reg_moments_from_geometry,
    _seg_seg_static_moments,
    _static_toeplitz_table,
)
from momwire.bspline import BSplineSolver

_ORACLE = Path(__file__).with_name("data") / "same_edge_oracle_968.npz"
C0 = 299792458.0
LONG_WIRE = [np.array([(0.0, 0.0, 0.0), (0.0, 4000.0, 0.0)])]
LONG_LAM = C0 / 15e6

_ACCEL_FLAGS = (
    "_HAVE_BSPLINE_REG_SWEPT_ACCEL",
    "_HAVE_BSPLINE_REG_SWEPT_EK_ACCEL",
    "_HAVE_BSPLINE_STATIC_ACCEL",
    "_HAVE_BSPLINE_STATIC_EK_ACCEL",
)


