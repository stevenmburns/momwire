# G-968-1: a window IS the sub-block
# ---------------------------------------------------------------------


@pytest.mark.parametrize("accel", [True, False], ids=["accel", "numpy"])
@pytest.mark.parametrize("ek_on", [False, True], ids=["reduced", "ek"])
@pytest.mark.parametrize("n_qp", [2, 4])
@pytest.mark.parametrize("max_d", [1, 2])
@pytest.mark.parametrize("N", [7, 12])
def test_every_window_equals_the_square_sub_block(
    N, max_d, n_qp, ek_on, accel, monkeypatch
):
    """Exactly, not approximately, on every route.

    The numpy arm is not decoration: the accelerator is absent on some
    platforms, and a windowed numpy einsum that transposed its two `wu`
    operands would still look plausible and be wrong on every off-diagonal
    block.
    """
    if not accel:
        for flag in _ACCEL_FLAGS:
            monkeypatch.setattr(bk, flag, False)
    h = 0.37
    seg = np.arange(N + 1) * h
    a = 5e-4
    ek = _EK(a=1.7e-3, group_i=None, group_j=None) if ek_on else None
    full_reg = _seg_seg_reg_moments_from_geometry(
        _seg_seg_reg_geometry(seg, a, max_d, n_qp, ek=ek), 0.77
    )
    full_st = _seg_seg_static_moments(seg, a, max_d, ek=ek)
    # Full height, one row, an interior run, the last rows, and EMPTY — the
    # last because a chunk loop can hand over a zero-width window at the end
    # of an edge and a silent shape error there would be a wrong answer, not
    # a crash.
    for r0, r1 in ((0, N), (0, 1), (2, 5), (N - 2, N), (3, 3)):
        win = slice(r0, r1)
        got_reg = _seg_seg_reg_moments_from_geometry(
            _seg_seg_reg_geometry(seg, a, max_d, n_qp, ek=ek, rows=win), 0.77
        )
        got_st = _seg_seg_static_moments(seg, a, max_d, ek=ek, rows=win)
        assert np.array_equal(got_reg, full_reg[:, :, r0:r1, :]), (r0, r1, "reg")
        assert np.array_equal(got_st, full_st[:, :, r0:r1, :]), (r0, r1, "static")


def test_a_window_is_not_secretly_the_transpose():
    """The one failure a sub-block comparison on a SYMMETRIC block would miss.

    A same-edge reg block is not symmetric in general, but it is close enough
    that a swapped row/column `wu` would still pass a loose tolerance. This
    asserts the block genuinely differs from its own transpose, so the
    equality above is testing what it claims.
    """
    h, a, N, max_d, n_qp = 0.37, 5e-4, 9, 2, 4
    seg = np.arange(N + 1) * h
    full = _seg_seg_reg_moments_from_geometry(
        _seg_seg_reg_geometry(seg, a, max_d, n_qp), 0.77
    )
    # p/P are the polynomial axes; i/j the segment axes. Swapping the segment
    # axes alone must change the block.
    assert not np.array_equal(full, np.swapaxes(full, 2, 3))


