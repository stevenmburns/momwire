"""Write `src/momwire/_leggauss_table.h` from `src/momwire/_leggauss_table.py`.

The C++ side of momwire (the razor-2p front half, `_razor_front_core.cpp`)
reads the same frozen Gauss-Legendre rules the Python solver does
(`momwire._quadrature.leggauss`), so neither depends on the host's LAPACK
eigensolver. The header is GENERATED from the Python table, never edited:
each rule's non-negative half, nodes then weights, as C99 hex-float literals
-- the table's own strings, copied character for character, so the bits
are the table's by construction. `tests/test_leggauss_header.py` holds the
committed header equal to this script's output byte for byte, and the C++
rules equal to `leggauss(n)` for every tabled order.

Usage (any platform; it reads the table, not numpy):

    python scripts/gen_leggauss_header.py           # rewrite the header
    python scripts/gen_leggauss_header.py --check   # exit 1 if it is stale
"""

from __future__ import annotations

import argparse
import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TABLE = ROOT / "src" / "momwire" / "_leggauss_table.py"
HEADER = ROOT / "src" / "momwire" / "_leggauss_table.h"


def _table():
    """`N_MAX` and `HALVES` read from the module's source (no import, so the
    script needs neither momwire nor numpy)."""
    tree = ast.parse(TABLE.read_text())
    values = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name):
            name = node.targets[0].id
            if name in ("N_MAX", "HALVES"):
                values[name] = ast.literal_eval(node.value)
    return values["N_MAX"], values["HALVES"]


def render() -> str:
    n_max, halves = _table()
    assert sorted(halves) == list(range(1, n_max + 1)), "the table is not 1..N_MAX"
    out = [
        "// The frozen Gauss-Legendre rules, orders 1..N_MAX. GENERATED by\n",
        "// scripts/gen_leggauss_header.py from src/momwire/_leggauss_table.py -- do\n",
        "// not edit. Each rule is its non-negative half (nodes ascending, the middle\n",
        "// node 0 included when n is odd), the table's own hex strings copied as C99\n",
        "// hex-float literals; `mw::leggauss` (in `_razor_front_core.cpp`) mirrors\n",
        "// `momwire._quadrature._from_half` to give the full rule.\n",
        "#pragma once\n",
        "\n",
        "namespace mw {\n",
        "namespace leggauss_table {\n",
        "\n",
        f"constexpr int N_MAX = {n_max};\n",
        "\n",
        "// OFFSET[n - 1] .. OFFSET[n]: rule n's half in NODES / WEIGHTS.\n",
    ]
    offsets = [0]
    nodes, weights = [], []
    for n in range(1, n_max + 1):
        xs, ws = halves[n]
        xs, ws = xs.split(), ws.split()
        assert len(xs) == len(ws) == (n + 1) // 2, f"order {n}: half has the wrong size"
        nodes += xs
        weights += ws
        offsets.append(len(nodes))
    out.append(f"constexpr int OFFSET[{len(offsets)}] = {{\n")
    for i in range(0, len(offsets), 12):
        out.append("    " + ", ".join(str(v) for v in offsets[i : i + 12]) + ",\n")
    out.append("};\n\n")
    for name, values in (("NODES", nodes), ("WEIGHTS", weights)):
        out.append(f"constexpr double {name}[{len(values)}] = {{\n")
        for i in range(0, len(values), 3):
            out.append("    " + ", ".join(values[i : i + 3]) + ",\n")
        out.append("};\n\n")
    out.append("}  // namespace leggauss_table\n")
    out.append("}  // namespace mw\n")
    return "".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if the header is stale")
    args = ap.parse_args()
    text = render()
    if args.check:
        if not HEADER.exists() or HEADER.read_text() != text:
            sys.exit(f"{HEADER} is stale: run scripts/gen_leggauss_header.py")
        return
    HEADER.write_text(text)
    print(f"wrote {HEADER}")


if __name__ == "__main__":
    main()
